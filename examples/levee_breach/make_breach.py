#!/usr/bin/env python3
# 解像堤防(DEM の標高で表した堤防)の破堤スケジュールを、規定底面運動
# (fn_bedmotion)の入力 — 窓付きの累積変位ファイル群とスナップショット表 —
# に変換する前処理。ENCflow 本体は変更しない(docs/users_guide/bedmotion.md)。
#
#   破堤口のセル矩形(列 I1..I2 × 行 J1..J2)の地盤高 z を、堤底の標高(floor)
#   まで時刻 t0〜t1(分)で下げる。各セルの累積変位は
#       d(t) = -(z0 - floor) * p(t),   p: 0 → 1 の進行率
#   で、堤防に沿う方向に中心から k セル離れたセルは遅れて始まり(拡幅)、
#   どのセルも開始から tdeep 分で堤底に達する(深さの進行):
#       開始 t_k = t0 + (t1 - t0 - tdeep) * k / kmax,  終了 t_k + tdeep
#   tdeep = t1 - t0(既定)なら全セル同時。p は折れ線なので、折れ点の時刻
#   すべてをスナップショットに出せば f_bminterp = 1 の線形補間で厳密になる。
#
#   堤底の標高は 3 通り: --floor VALUE(一定値)、--floor-col C(各行で列 C の
#   地盤高 = 南北に走る堤防の堤内地側法尻の列)、--floor-row R(東西の堤防)。
#   変位ファイルは z と同じテキスト行列(行 1 が北)で、窓(破堤口の矩形)
#   だけを書き、表の各行末に i1 j1 ni nj を付ける。GeoTIFF/bil の z を使う
#   計算では f_input_mode に合わせて別途変換すること。
#
# 例(この例題。北から 48〜52 行、列 21〜22 の堤防を 70〜90 分で破堤。
#     中央の行から 10 分で堤底、両側へ拡幅):
#   python3 make_breach.py --z z.txt --cols 21 22 --rows 48 52 --floor-col 23 \
#       --t0 70 --t1 90 --tdeep 10 --out bm
import argparse, os, sys
import numpy as np

ap = argparse.ArgumentParser(description='levee breach schedule -> fn_bedmotion inputs')
ap.add_argument('--z', required=True, help='bed elevation (text matrix, row 1 = north)')
ap.add_argument('--cols', nargs=2, type=int, required=True, metavar=('I1', 'I2'), help='breach columns (1-based, inclusive)')
ap.add_argument('--rows', nargs=2, type=int, required=True, metavar=('J1', 'J2'), help='breach rows (1-based, inclusive)')
g = ap.add_mutually_exclusive_group(required=True)
g.add_argument('--floor', type=float, help='floor elevation of the breach (m, constant)')
g.add_argument('--floor-col', type=int, help='take the floor of each row from this column (N-S levee: landside toe)')
g.add_argument('--floor-row', type=int, help='take the floor of each column from this row (E-W levee)')
ap.add_argument('--t0', type=float, required=True, help='start of the breach (min from t0 of the run)')
ap.add_argument('--t1', type=float, required=True, help='end of the breach: full width at full depth (min)')
ap.add_argument('--tdeep', type=float, default=None, help='time for one cell to reach the floor (min; default t1 - t0 = all cells together)')
ap.add_argument('--center', type=int, default=None, help='index (row or column) of the first cell to fail (default: middle)')
ap.add_argument('--out', default='bm', help='output directory (default bm)')
ap.add_argument('--prefix', default='breach', help='file prefix (default breach)')
a = ap.parse_args()

z = np.loadtxt(a.z)
ny, nx = z.shape
i1, i2 = sorted(a.cols); j1, j2 = sorted(a.rows)
if i1 < 1 or i2 > nx or j1 < 1 or j2 > ny:
    sys.exit('breach rectangle outside the grid (%d x %d)' % (nx, ny))
ni, nj = i2 - i1 + 1, j2 - j1 + 1
tdeep = a.tdeep if a.tdeep is not None else a.t1 - a.t0
if not (0 < tdeep <= a.t1 - a.t0):
    sys.exit('need 0 < tdeep <= t1 - t0')

# 堤底の標高(窓の各セル)
floor = np.empty((nj, ni))
for jj in range(nj):
    for ii in range(ni):
        if a.floor is not None:
            floor[jj, ii] = a.floor
        elif a.floor_col is not None:
            floor[jj, ii] = z[j1 - 1 + jj, a.floor_col - 1]
        else:
            floor[jj, ii] = z[a.floor_row - 1, i1 - 1 + ii]
z0 = z[j1-1:j2, i1-1:i2]
drop = np.maximum(z0 - floor, 0.0)            # 下げ幅(堤底より低いセルは動かさない)

# 堤防に沿う方向(長い辺)と中心からの距離 k
along_j = nj >= ni
n_along = nj if along_j else ni
first = j1 if along_j else i1
center = a.center if a.center is not None else first + (n_along - 1) // 2
if not (first <= center < first + n_along):
    sys.exit('--center must lie inside the breach rectangle')
kk = np.abs(np.arange(first, first + n_along) - center)
kmax = max(int(kk.max()), 1)
tstart = a.t0 + (a.t1 - a.t0 - tdeep) * kk / kmax     # 各列(行)の開始時刻 (min)
if kk.max() == 0:
    tstart[:] = a.t0

def progress(t):
    p = np.clip((t - tstart) / tdeep, 0.0, 1.0)      # 沿い方向の各位置
    return np.tile(p[:, None], (1, ni)) if along_j else np.tile(p[None, :], (nj, 1))

# スナップショット時刻: 0、t0、t1、各列(行)の開始・終了(折れ点を全部出す)
times = sorted(set([0.0, a.t0, a.t1] + list(np.round(tstart, 6)) + list(np.round(tstart + tdeep, 6))))
os.makedirs(a.out, exist_ok=True)
with open(os.path.join(a.out, 'bmlist.txt'), 'w') as f:
    f.write('# levee breach by prescribed bed motion (generated by make_breach.py)\n')
    f.write('# cells: columns %d..%d, rows %d..%d; breach %g..%g min, tdeep %g min, center %d\n'
            % (i1, i2, j1, j2, a.t0, a.t1, tdeep, center))
    f.write('# time(s)   file                     i1  j1  ni  nj   (window; zero outside)\n')
    for k, t in enumerate(times):
        d = -drop * progress(t)
        fn = '%s_%02d.txt' % (a.prefix, k)
        np.savetxt(os.path.join(a.out, fn), d, fmt='%.4f')
        f.write('%10.1f   %-24s %3d %3d %3d %3d\n' % (t * 60.0, a.out + '/' + fn, i1, j1, ni, nj))

print('breach rectangle: columns %d..%d (%d), rows %d..%d (%d); along %s, center %d'
      % (i1, i2, ni, j1, j2, nj, 'rows (N-S levee)' if along_j else 'columns (E-W levee)', center))
print('crest z0: %.3f..%.3f m, floor: %.3f..%.3f m, max lowering: %.3f m'
      % (z0.min(), z0.max(), floor.min(), floor.max(), drop.max()))
print('schedule (min): start %s, end %s' % (np.array2string(np.round(tstart, 2)), np.array2string(np.round(tstart + tdeep, 2))))
print('written: %s/bmlist.txt and %d displacement files (window %d x %d)' % (a.out, len(times), ni, nj))
print('add to the parameter file:\n  &list_sysparam ... fn_bedmotion = \'-\' ... /\n  &list_bedmotion\n    fn_bmlist = \'%s/bmlist.txt\'\n  /' % a.out)
